// Generates src/mime_table.rs from mime-types/mime-db (the table Express, send and serve-static
// use), so static files, res.sendFile() and res.type() pick the same Content-Type as Express.
//
//   node scripts/gen-mime-table.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));
const mime = require('mime-types');
const typesVersion = require('mime-types/package.json').version;
const dbVersion = require('mime-db/package.json').version;

const entries = Object.keys(mime.types)
  .sort()
  .map((ext) => [ext, mime.contentType(ext)]);

for (const [ext, ct] of entries) {
  if (!/^[\x21-\x7e]+$/.test(ext) || !/^[\x20-\x7e]+$/.test(ct)) {
    throw new Error(`unexpected entry ${ext} -> ${ct}`);
  }
}

const lines = entries.map(([ext, ct]) => `    (${JSON.stringify(ext)}, ${JSON.stringify(ct)}),`);
const out = `//! Extension -> Content-Type table, generated by scripts/gen-mime-table.mjs from
//! mime-types ${typesVersion} / mime-db ${dbVersion}. Do not edit by hand.

/// \`(extension, Content-Type)\` sorted by extension; the Content-Type is what
/// \`mime-types.contentType(extension)\` returns (charset included).
static MIME_TYPES: &[(&str, &str)] = &[
${lines.join('\n')}
];

/// Content-Type for a file extension (without the dot, any case), as \`mime-types\` gives it.
pub fn content_type_for_extension(ext: &str) -> Option<&'static str> {
    let lower;
    let key = if ext.bytes().any(|b| b.is_ascii_uppercase()) {
        lower = ext.to_ascii_lowercase();
        lower.as_str()
    } else {
        ext
    };
    MIME_TYPES
        .binary_search_by(|(e, _)| e.cmp(&key))
        .ok()
        .map(|i| MIME_TYPES[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_matches_mime_types() {
        assert!(MIME_TYPES.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(content_type_for_extension("js"), Some("text/javascript; charset=utf-8"));
        assert_eq!(content_type_for_extension("JSON"), Some("application/json; charset=utf-8"));
        assert_eq!(content_type_for_extension("png"), Some("image/png"));
        assert_eq!(content_type_for_extension("nope-not-a-type"), None);
    }
}
`;
writeFileSync(join(root, 'src', 'mime_table.rs'), out);
console.log(`wrote ${entries.length} extensions to src/mime_table.rs`);
